/**
 * @module features/analytics/test/term-hint
 * @description PRD-66 FR-14b: термин с подсказкой — заголовок колонки или подпись плитки.
 *
 * Без значка подсказка невидима: читатель не знает, что на термин можно навести. Значок обязан
 * держаться при последнем слове: жалоба владельца 2026-09-25 — в узкой колонке значок уходил на
 * отдельную строку, и заголовок читался оторванным от своей колонки.
 *
 * Поэтому значок — не элемент рядом с термином, а псевдоэлемент самого термина
 * (`.tb-term-hint__term::after` в `tb-components.css`): неразрывный пробел и иконка маской. Пробел
 * — ТЕКСТ, а не блок, и перенос не отрывает его от слова; соединитель U+2060 перед блочным
 * значком браузер не соблюдал (вскрыто приёмкой 5.2). Термин при этом остаётся одним текстом:
 * так его читает экранный диктор и находит поиск по странице.
 *
 * У числовой колонки заголовок стоит справа, над числами (`align="end"`): ячейка заголовка
 * DataGrid — гибкий ряд, поэтому обёртка растягивается на всю ширину (`ou-grow`) и
 * выравнивает текст по правому краю (`ou-text--end`).
 */
import type { ReactNode } from "react";
import { Tooltip } from "@skillum/ui-kit";

/** Свойства термина с подсказкой. */
export interface TermHintProps {
  /** Сам термин — то, что читается в заголовке или под числом плитки. */
  term: ReactNode;
  /** Текст подсказки — дословно из эскиза. */
  hint: string;
  /** `end` — заголовок числовой колонки: стоит справа, над числами. */
  align?: "start" | "end";
}

/**
 * Термин с подсказкой (FR-14b).
 *
 * @param props - термин, текст подсказки и выравнивание
 * @returns триггер подсказки; значок рисует стиль термина и держится при последнем слове
 */
export function TermHint({ term, hint, align = "start" }: TermHintProps) {
  const tip = (
    // tabIndex: подсказка открывается и с клавиатуры (`:focus-within`), как в эскизе.
    // `tb-term-hint` — метка для раскладки заголовка в `tb-components.css`.
    <Tooltip content={hint} placement="bottom" wrap tabIndex={0} className="tb-term-hint">
      <span className="tb-term-hint__term">{term}</span>
    </Tooltip>
  );
  return align === "end" ? <span className="ou-grow ou-text--end">{tip}</span> : tip;
}
